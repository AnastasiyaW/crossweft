LANGUAGES = {"en": EN, "ru": RU}


def table(language: str) -> dict:
    return LANGUAGES[language]


def key_mismatches() -> list[str]:
    """Keys present in one language table but not in another (self-test)."""
    problems = []
    base = EN
    for name, other in LANGUAGES.items():
        for section, values in base.items():
            theirs = other.get(section, {})
            missing = sorted(set(values) - set(theirs))
            extra = sorted(set(theirs) - set(values))
            if missing:
                problems.append(f"{name}.{section} lacks {missing}")
            if extra:
                problems.append(f"{name}.{section} has extra {extra}")
    return problems
