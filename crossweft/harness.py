"""`crossweft agents` -- the repository carries its own agent harness.

A repository that adopts crossweft must not depend on each developer installing
a plugin: any coding agent that opens it should pick the seams up as part of the
architecture. `crossweft agents` writes, idempotently and never over someone
else's text:

- `AGENTS.md`: a marked block with the working rules. Codex, Copilot, Cursor and
  Claude Code read AGENTS.md (Claude Code directly when there is no CLAUDE.md,
  .claude/CLAUDE.md or CLAUDE.local.md; otherwise through an `@AGENTS.md`
  import, which is added to the first of those files that exists);
- `.claude/settings.json`: the SessionStart, PostToolUse and Stop hooks, merged
  into whatever the file already holds (a group that also holds someone
  else's hook is never changed: ours gets a group of its own);
- `.claude/skills/crossweft/SKILL.md`: the working skill (fix, attest, map a
  repository from scratch), copied from the installed package.

How the hooks start crossweft is declared once, as `agent.command` in
crossweft.json (default `crossweft`; `agents --command` and `init --command`
record it). With `"agent": {"harness": true}` (`init` and `agents` set it),
`crossweft check` fails when any of these is missing or out of date, or when a
hook is not exactly `<agent.command> hook claude-code <event>`: the harness is
part of the architecture and is guarded like any other seam.

Every file is written atomically, in the line endings it already uses.

This module depends on nothing else in crossweft, so the engine can call it.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
from pathlib import Path

CONFIG_FILE = "crossweft.json"   # engine.CONFIG_FILE; this module imports nothing from it
SKILL_SOURCE = Path(__file__).resolve().parent / "skills" / "crossweft" / "SKILL.md"
SKILL_TARGET = ".claude/skills/crossweft/SKILL.md"
SETTINGS = ".claude/settings.json"
BLOCK_BEGIN = "<!-- crossweft-agents:begin (generated by `crossweft agents`; re-run it to update) -->"
BLOCK_END = "<!-- crossweft-agents:end -->"
# the markers of any version, where `agents` writes them: at the start of a line
# (the same text quoted inside a sentence is someone's prose, not a block)
BEGIN_LINE = re.compile(r"^<!-- crossweft-agents:begin", re.MULTILINE)
END_LINE = re.compile("^" + re.escape(BLOCK_END), re.MULTILINE)
SKILL_MARKER = ("<!-- generated by `crossweft agents` from the installed crossweft package; "
                "run it again to update, do not edit -->")
DEFAULT_COMMAND = "crossweft"
EDIT_MATCHER = "Edit|Write|MultiEdit|NotebookEdit"
EVENTS = (("SessionStart", "session-start", None, 30),
          ("PostToolUse", "post-edit", EDIT_MATCHER, 60),
          ("Stop", "stop", None, 120))
# Any of these makes Claude Code read the CLAUDE.md files instead of AGENTS.md
# (https://code.claude.com/docs/en/memory#agents-md), so one of them must
# import it; `agents` adds the import to the first one that exists.
CLAUDE_FILES = (("CLAUDE.md", "@AGENTS.md"), (".claude/CLAUDE.md", "@../AGENTS.md"),
                ("CLAUDE.local.md", "@AGENTS.md"))
# Whether the project's hooks run is proved by running `<agent.command> --version`
# in the shell Claude Code uses; crossweft answers in well under a second, and the
# plugin's shortest hook timeout is 30s.
LAUNCHER_PROBE_TIMEOUT = 10
# A loaded machine can take longer to start a shell: CROSSWEFT_LAUNCHER_PROBE_TIMEOUT
# raises the limit, capped below the plugin's 30s hook timeout so the probe never
# eats the whole hook. A probe that runs out only makes the plugin check by itself.
LAUNCHER_PROBE_TIMEOUT_MAX = 25


def launcher_probe_timeout() -> float:
    raw = os.environ.get("CROSSWEFT_LAUNCHER_PROBE_TIMEOUT")
    if raw is None or not raw.strip():
        return LAUNCHER_PROBE_TIMEOUT
    try:
        value = float(raw)
    except ValueError:
        raise HarnessError(f"CROSSWEFT_LAUNCHER_PROBE_TIMEOUT={raw!r}: must be a number of seconds") from None
    if value <= 0:
        raise HarnessError(f"CROSSWEFT_LAUNCHER_PROBE_TIMEOUT={raw!r}: must be above 0")
    return min(value, LAUNCHER_PROBE_TIMEOUT_MAX)
VERSION_ANSWER = re.compile(r"^crossweft \d", re.MULTILINE)   # argparse's `--version` line


class HarnessError(Exception):
    """A file the harness must change is unreadable or belongs to someone else."""


class HarnessWriteError(HarnessError):
    """Writing failed part-way; the message says what was already written."""


def agents_block(model_dir: str) -> str:
    return f"""{BLOCK_BEGIN}
## Component seams (crossweft)

This repository keeps a map of its components and of every place where two of
them must agree -- routes, headers, protocol versions, DTO fields, env vars,
pipe names, duplicated algorithms -- in `{model_dir}`, and `crossweft check`
verifies the map against the code. Agents write and maintain the map, and
the check makes sure it cannot drift from the code.

- Before editing a file another component depends on, run
  `crossweft impact <path>` (or the `impact` tool of `crossweft mcp`): it names
  the file on the other side and the guard that compares them. Change both
  sides.
- Before you finish, `crossweft check` must print `RESULT: PASS` (exit 0;
  1 = problems, 2 = no verdict, which is never a pass). `crossweft check
  --changed HEAD` is a fast pre-commit check, not the final one. For Claude
  Code the hooks in `.claude/settings.json` do this for you: after each edit
  they name the other side, and they send you back while a seam disagrees.
- When you add a component, a connection, or a value two places must share,
  put it on the map in the same change: a block, a link with anchors and
  `contract.enforcement`, and a guard that reads both sides for every
  hand-written seam (`crossweft discover` suggests guards; `crossweft import`
  derives them when one side is an OpenAPI or .proto schema). The
  `crossweft` skill has the full procedure, including mapping a repository
  from scratch.
- Never weaken a guard, widen a regex, add an `allow` entry or a finding, run
  `crossweft baseline` (it is for adoption only), or attest a pair with
  `--other-side-unchanged` without re-reading every region, just to make the
  check pass; each needs a concrete reason.
- If `crossweft` is not on the shell's PATH, run the same commands as
  `python -m crossweft ...` (`python3` where that is the name).
{BLOCK_END}
"""


def skill_text() -> str:
    source = SKILL_SOURCE.read_text(encoding="utf-8")
    if not source.startswith("---\n"):
        raise HarnessError(f"{SKILL_SOURCE} has no front matter")
    end = source.index("\n---\n", 4) + len("\n---\n")
    return source[:end] + SKILL_MARKER + "\n" + source[end:]


def hook_command(command: str, event: str) -> str:
    return f"{command} hook claude-code {event}"


def configured_command(root: Path) -> str:
    """`agent.command` in crossweft.json -- how the hooks start crossweft, the
    one value `agents` writes into them and `check` compares them with."""
    agent = _read_json(root / CONFIG_FILE).get("agent", {})
    command = agent.get("command", DEFAULT_COMMAND) if isinstance(agent, dict) else None
    if not isinstance(command, str) or not command.strip():
        raise HarnessError(f"{CONFIG_FILE}: agent.command must be a non-empty string")
    return command.strip()


def _launcher(command: object, event: str) -> str | None:
    """`<launcher>` of a hook command shaped like the ones `agents` writes
    (`<launcher> hook claude-code <event>`), else None."""
    suffix = f" hook claude-code {event}"
    if not isinstance(command, str) or not command.strip().endswith(suffix):
        return None
    return command.strip()[:-len(suffix)].strip() or None


