def _read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError as exc:
        raise HarnessError(f"{path} is not UTF-8 text ({exc.reason} at byte {exc.start}) -- "
                           "convert it to UTF-8") from exc
    except OSError as exc:
        raise HarnessError(f"{path}: {exc}") from exc


def _read_json(path: Path, text: str | None = None) -> dict:
    try:
        data = json.loads(_read_text(path) if text is None else text)
    except ValueError as exc:
        raise HarnessError(f"{path} is not valid JSON ({exc}) -- fix it first") from exc
    if not isinstance(data, dict):
        raise HarnessError(f"{path} must hold a JSON object")
    return data


def _json_indent(text: str) -> int | str:
    """The indentation a JSON file already uses (2 for a new or flat one)."""
    match = re.search(r"^([ \t]+)\S", text, re.MULTILINE)
    if not match:
        return 2
    whitespace = match.group(1)
    return len(whitespace) if set(whitespace) == {" "} else whitespace   # tabs: as they are


def _read_only(path: Path) -> bool:
    return path.is_file() and not os.access(path, os.W_OK)


def write_text(path: Path, text: str) -> None:
    """Replace `path` with `text` (LF line breaks) through a temporary file in the
    same directory and os.replace: an interrupted write leaves the old file,
    never half of the new one. The file keeps its line endings (CRLF or LF)
    and its permissions; a new file gets LF and the usual permissions. A
    symlink stays a link (its target is replaced); a read-only file is an
    error, as a plain write would be."""
    if path.is_symlink():
        path = path.resolve()
    if _read_only(path):
        raise PermissionError(f"{path} is read-only")
    existing = path.is_file()
    newline = "\r\n" if existing and b"\r\n" in path.read_bytes() else "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(f".{path.name}.{os.getpid()}.crossweft-tmp")
    try:
        with open(temp, "wb") as handle:
            handle.write(text.replace("\n", newline).encode("utf-8"))
        if existing:
            os.chmod(temp, path.stat().st_mode & 0o7777)
        os.replace(temp, path)
    except BaseException:
        try:
            temp.unlink(missing_ok=True)   # our own temporary file, never the target
        except OSError:
            pass   # the error being raised says more than a failed cleanup
        raise


