def _hook_entries(settings: dict, name: str) -> list:
    hooks = settings.get("hooks", {})
    groups = hooks.get(name, []) if isinstance(hooks, dict) else []
    return groups if isinstance(groups, list) else []


def _candidates(settings: dict) -> dict[str, list[tuple[dict, dict, str]]]:
    """Per hook event: every (group, hook, launcher) shaped like a crossweft hook."""
    found: dict[str, list[tuple[dict, dict, str]]] = {}
    for name, event, _, _ in EVENTS:
        found[name] = []
        for group in _hook_entries(settings, name):
            if not isinstance(group, dict) or not isinstance(group.get("hooks"), list):
                continue
            for hook in group["hooks"]:
                launcher = _launcher(hook.get("command"), event) if isinstance(hook, dict) \
                    else None
                if launcher:
                    found[name].append((group, hook, launcher))
    return found


def _shared_launchers(found: dict) -> set[str]:
    """Launchers that start the hook of every event: a complete set an earlier
    `agents` wrote, which `agents` may rewrite to the current command. (Whether
    a launcher starts crossweft is not decided here: `check` compares with the
    declared agent.command, the plugin asks the launcher itself.)"""
    return set.intersection(*({launcher for _, _, launcher in found[name]}
                              for name, _, _, _ in EVENTS))


_PLAIN_MATCHER = re.compile(r"[A-Za-z0-9_\- ,|]*")


def _matches(matcher: object, tool: str) -> bool:
    """Claude Code's matcher rules (https://code.claude.com/docs/en/hooks#matcher):
    "*", "" or no matcher match every tool; letters, digits, _ - space , and |
    only are exact tool names separated by | or ,; anything else is a regular
    expression."""
    if matcher is None or matcher in ("", "*"):
        return True
    if not isinstance(matcher, str):
        return False
    if _PLAIN_MATCHER.fullmatch(matcher):
        return tool in {part.strip() for part in re.split(r"[|,]", matcher)}
    try:
        return re.search(matcher, tool) is not None
    except re.error:
        return False   # a pattern Python cannot read counts as not matching: reported


def _matches_edits(group: dict) -> bool:
    return all(_matches(group.get("matcher"), tool) for tool in ("Edit", "Write"))


def _hook_problems(settings: dict, command: str) -> list[tuple[str, str]]:
    """(key, message) for what keeps the hooks from starting `command`, the
    declared agent.command, at each event."""
    fix = "run `crossweft agents`"
    found_problems: list[tuple[str, str]] = []
    if settings.get("disableAllHooks") is True:
        found_problems.append(("agents:hooks", f'{SETTINGS} sets "disableAllHooks": true, so '
                               "none of the seam hooks runs -- remove it (`crossweft agents` "
                               "does not change it)"))
    found = _candidates(settings)
    for name, event, matcher, _ in EVENTS:
        wanted = hook_command(command, event)
        ours = [group for group, hook, _ in found[name] if hook["command"].strip() == wanted]
        if not ours:
            others = sorted({hook["command"].strip() for _, hook, _ in found[name]})
            seen = f" (it runs {', '.join(f'`{c}`' for c in others)})" if others else ""
            found_problems.append((f"agents:hooks:{event}", f"{SETTINGS} has no {name} hook "
                                   f"running `{wanted}`{seen}, and {CONFIG_FILE} declares "
                                   f"agent.command `{command}` -- {fix} (with --command if "
                                   "crossweft starts another way here)"))
        elif matcher and not any(_matches_edits(group) for group in ours):
            found_problems.append((f"agents:hooks:{event}", f"the crossweft {name} hook does "
                                   f"not match Edit and Write, so edits go unreported -- {fix}"))
    return found_problems


def project_hooks_run(root: Path, cwd: Path) -> bool:
    """True when the project's own settings run all three crossweft hooks AND
    they would start crossweft here, so the plugin can stay quiet. Configured is
    not enough: a plugin-only user has no `crossweft` on PATH (the project hook
    fails with 127), and `echo` or `true` hooks check nothing -- a quiet plugin
    would let drift through."""
    path = root / SETTINGS
    if not path.is_file():
        return False
    started = os.environ.get("CLAUDE_PROJECT_DIR")
    if started and Path(started).resolve() != root.resolve():
        # Claude Code reads .claude/settings.json from the directory the session
        # started in (https://code.claude.com/docs/en/settings), not from ours
        return False
    try:
        settings = _read_json(path)
        command = configured_command(root)
    except HarnessError:
        return False
    return not _hook_problems(settings, command) and _answers_as_crossweft(command, root, cwd)


def _hook_shell() -> str | None:
    """The shell Claude Code runs hook commands in. bin/crossweft (how the plugin
    starts) exports the bash running it as CROSSWEFT_SHELL; otherwise bash from
    PATH on Windows (Git Bash -- never WSL's System32 bash, another system) and
    sh elsewhere (https://code.claude.com/docs/en/hooks). None: nothing to ask."""
    shell = os.environ.get("CROSSWEFT_SHELL")
    if shell:
        return shell
    if os.name == "nt":
        bash = shutil.which("bash")
        return bash if bash and "system32" not in bash.lower() else None
    return shutil.which("sh")


def _answers_as_crossweft(command: str, root: Path, cwd: Path) -> bool:
    """Run `<command> --version` as Claude Code would run the hook -- its shell
    (quoting, $CLAUDE_PROJECT_DIR), the hook's working directory, without the
    plugin's own variables -- and require crossweft's answer. A program that is
    missing, `echo`, `true`, a module that is not runnable, or no shell to ask:
    the project's hooks do not run crossweft."""
    shell = _hook_shell()
    if not shell:
        return False
    env = {key: value for key, value in os.environ.items()
           if not key.startswith("CLAUDE_PLUGIN_")}
    env.setdefault("CLAUDE_PROJECT_DIR", str(root))
    try:
        probe = subprocess.run([shell, "-c", f"{command} --version"], cwd=cwd, env=env,
                               stdin=subprocess.DEVNULL, capture_output=True,
                               timeout=launcher_probe_timeout())
    except (OSError, subprocess.TimeoutExpired):
        return False
    return probe.returncode == 0 and bool(
        VERSION_ANSWER.search(probe.stdout.decode("utf-8", errors="replace")))


def _merge_settings(settings: dict, command: str) -> list[str]:
    """Merge the three hooks, each started by `command`, into `settings`."""
    changes = []
    hooks = settings.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise HarnessError(f"{SETTINGS}: 'hooks' must be an object")
    found = _candidates(settings)
    shared = _shared_launchers(found)

    def installed(launcher: str) -> bool:
        # an earlier run's: it names crossweft, or it starts the hook of every
        # event (a complete set written with a custom --command). Hooks merely
        # shaped like ours, even at two events, belong to another tool.
        return "crossweft" in launcher or launcher in shared

    for name, event, matcher, timeout in EVENTS:
        wanted = hook_command(command, event)
        ours = [(group, hook) for group, hook, launcher in found[name]
                if hook["command"] == wanted or installed(launcher)]
        for group, hook in ours:
            if hook["command"] != wanted:
                hook["command"] = wanted
                changes.append(f"{SETTINGS}: {name} hook now runs `{wanted}`")
        if ours and (not matcher or any(_matches_edits(group) for group, _ in ours)):
            continue
        # a group that holds only our hook is ours to fix; a shared one is not
        own = [group for group, _ in ours
               if all(any(hook is mine for _, mine in ours) for hook in group["hooks"])]
        if own:
            own[0]["matcher"] = matcher
            changes.append(f"{SETTINGS}: {name} matcher set to {matcher}")
            continue
        group = {"hooks": [{"type": "command", "command": wanted, "timeout": timeout}]}
        if matcher:
            group = {"matcher": matcher, **group}
        groups = hooks.setdefault(name, [])
        if not isinstance(groups, list):
            raise HarnessError(f"{SETTINGS}: hooks.{name} must be a list")
        groups.append(group)
        changes.append(f"{SETTINGS}: added the {name} hook (`{wanted}`)")
    return changes


def _with_block(text: str, block: str) -> str:
    """`text` with one crossweft block, the current one, where the first block
    was. Every marked block is crossweft's own text, so extra ones go."""
    spans = []
    begin = BEGIN_LINE.search(text)
    while begin:
        end_marker = END_LINE.search(text, begin.start())
        if not end_marker:
            raise HarnessError("AGENTS.md has a crossweft block without its end marker -- "
                               f"restore `{BLOCK_END}` or delete the block")
        end = end_marker.end()
        if text[end:end + 1] == "\n":
            end += 1
        spans.append((begin.start(), end))
        begin = BEGIN_LINE.search(text, end)
    if not spans:
        return block if not text else text.rstrip("\n") + "\n\n" + block
    kept = [text[end:nxt] for (_, end), (nxt, _) in zip(spans, spans[1:])]
    return text[:spans[0][0]] + block + "".join(kept) + text[spans[-1][1]:]


def _claude_files(root: Path) -> list[tuple[Path, str]]:
    """The files that make Claude Code read CLAUDE.md files instead of AGENTS.md,
    with the import line each would need. Empty: Claude Code reads AGENTS.md."""
    return [(root / rel, line) for rel, line in CLAUDE_FILES if (root / rel).is_file()]


def _imports_agents(text: str) -> bool:
    return any(line.strip().startswith(("@AGENTS.md", "@./AGENTS.md", "@../AGENTS.md"))
               for line in text.splitlines())


def _brings_agents(path: Path, text: str, root: Path) -> bool:
    """Does this CLAUDE file give Claude Code the AGENTS.md rules: it imports
    AGENTS.md, or it is AGENTS.md (a symlink to it)?"""
    return _imports_agents(text) or path.resolve() == (root / "AGENTS.md").resolve()


def install(root: Path, model_dir: str, command: str = DEFAULT_COMMAND,
            dry_run: bool = False) -> list[str]:
    """Write the harness; returns what changed. `command` is how the hooks start
    crossweft -- the caller records it as agent.command. Raises HarnessError,
    writing nothing, when a file it must change is not valid, not its own or
    read-only, and HarnessWriteError, naming what was written, when a write
    fails."""
    writes: dict[Path, str] = {}
    changes: list[str] = []

    settings_path = root / SETTINGS
    raw_settings = _read_text(settings_path) if settings_path.is_file() else ""
    settings = _read_json(settings_path, raw_settings) if settings_path.is_file() else {}
    before = json.dumps(settings, sort_keys=True)
    changes += _merge_settings(settings, command)
    if json.dumps(settings, sort_keys=True) != before or not settings_path.is_file():
        writes[settings_path] = json.dumps(settings, indent=_json_indent(raw_settings),
                                           ensure_ascii=False) + "\n"

    agents_path = root / "AGENTS.md"
    old = _read_text(agents_path) if agents_path.is_file() else ""
    new = _with_block(old, agents_block(model_dir))
    if new != old:
        writes[agents_path] = new
        blocks = len(BEGIN_LINE.findall(old))
        if not agents_path.exists():
            changes.append("AGENTS.md: created")
        elif blocks > 1:
            changes.append("AGENTS.md: kept one crossweft block, the current one")
        elif blocks:
            changes.append("AGENTS.md: updated the crossweft block")
        else:
            changes.append("AGENTS.md: added the crossweft block")

    claude = [(path, line, _read_text(path)) for path, line in _claude_files(root)]
    if claude and not any(_brings_agents(path, text, root) for path, _, text in claude):
        path, line, text = claude[0]
        names = ", ".join(p.relative_to(root).as_posix() for p, _, _ in claude)
        writes[path] = text.rstrip("\n") + f"\n\n{line}\n"
        changes.append(f"{path.relative_to(root).as_posix()}: added `{line}` (with {names} "
                       "present, Claude Code reads the CLAUDE.md files instead of AGENTS.md)")

    skill_path = root / SKILL_TARGET
    wanted = skill_text()
    if skill_path.is_file():
        current = _read_text(skill_path)
        if SKILL_MARKER not in current:
            raise HarnessError(f"{SKILL_TARGET} exists and was not generated by crossweft -- "
                               "move it away or rename the skill, then run again")
        if current != wanted:
            writes[skill_path] = wanted
            changes.append(f"{SKILL_TARGET}: updated")
    else:
        writes[skill_path] = wanted
        changes.append(f"{SKILL_TARGET}: created")

    read_only = [path.relative_to(root).as_posix() for path in writes if _read_only(path)]
    if read_only:
        raise HarnessError(f"{', '.join(read_only)} must change but is read-only -- make it "
                           "writable, then run again")
    if not dry_run:
        written: list[str] = []
        for path, text in writes.items():
            rel = path.relative_to(root).as_posix()
            try:
                write_text(path, text)
            except OSError as exc:
                raise HarnessWriteError(
                    f"could not write {rel} ({exc}); " + (
                        f"already written: {', '.join(written)}" if written
                        else "nothing was written") + " -- fix the cause and run it again"
                ) from exc
            written.append(rel)
    return changes


def problems(root: Path, model_dir: str) -> list[tuple[str, str, str]]:
    """(key, message, path) for every part of the harness that is missing or
    stale. Used by `crossweft check` when agent.harness is true."""
    fix = "run `crossweft agents`"
    found: list[tuple[str, str, str]] = []
    settings_path = root / SETTINGS
    if not settings_path.is_file():
        found.append(("agents:hooks", f"{SETTINGS} is missing, so Claude Code sessions run "
                                      f"without the seam hooks -- {fix}", SETTINGS))
    else:
        try:
            settings = _read_json(settings_path)
            command = configured_command(root)
        except HarnessError as exc:
            found.append(("agents:hooks", f"{exc} -- the seam hooks cannot run", SETTINGS))
        else:
            found += [(key, message, SETTINGS)
                      for key, message in _hook_problems(settings, command)]

    agents_path = root / "AGENTS.md"
    try:
        text = _read_text(agents_path) if agents_path.is_file() else ""
    except HarnessError as exc:
        found.append(("agents:agents-md", f"{exc} -- the crossweft block cannot be read",
                      "AGENTS.md"))
    else:
        blocks = len(BEGIN_LINE.findall(text))
        if blocks > 1:
            found.append(("agents:agents-md", f"AGENTS.md has {blocks} crossweft blocks and "
                          f"agents read every one -- {fix} (it keeps the current one)",
                          "AGENTS.md"))
        elif agents_block(model_dir) not in text:
            state = "is out of date" if blocks else "is missing"
            found.append(("agents:agents-md", f"the crossweft block in AGENTS.md {state} -- "
                          f"{fix}", "AGENTS.md"))

    claude = _claude_files(root)
    if claude:
        rel = claude[0][0].relative_to(root).as_posix()
        try:
            imported = any(_brings_agents(path, _read_text(path), root) for path, _ in claude)
        except HarnessError as exc:
            found.append(("agents:claude-md", f"{exc} -- cannot tell whether it imports "
                          "AGENTS.md", rel))
        else:
            if not imported:
                names = ", ".join(path.relative_to(root).as_posix() for path, _ in claude)
                found.append(("agents:claude-md", f"with {names} present Claude Code reads the "
                              "CLAUDE.md files instead of AGENTS.md, and none of them imports "
                              f"it -- add `{claude[0][1]}` to {rel} or {fix}", rel))

    skill_path = root / SKILL_TARGET
    if not skill_path.is_file():
        found.append(("agents:skill", f"{SKILL_TARGET} is missing -- {fix}", SKILL_TARGET))
    else:
        try:
            stale = _read_text(skill_path) != skill_text()
        except HarnessError as exc:
            found.append(("agents:skill", f"{exc} -- {fix}", SKILL_TARGET))
        else:
            if stale:
                found.append(("agents:skill", f"{SKILL_TARGET} differs from the installed "
                              f"crossweft's skill -- {fix}", SKILL_TARGET))
    return found
